    // Place a bridge block one step ahead of the camera in the gap
    placeBlock(camera) {
        let f = new Vector3();
        f.set(camera.at);
        f.sub(camera.eye);
        f.normalize();

        let tx = camera.eye.elements[0] + f.elements[0] * 1.5;
        let tz = camera.eye.elements[2] + f.elements[2] * 1.5;

        let mx = Math.floor((tx + 5) / 0.5 + 16);
        let mz = Math.floor(tz / 0.5 + 16);

        // Check bounds
    if (mx < 0 || mx >= 32 || mz < 0 || mz >= 32) return false;

    if (mx >= 10 && mx <= 20 && this.map[mz][mx] === 0) {
        this.objects.push({ x: mx, z: mz, y: 0, texture: 1 });
        return true;
    }
    return false;
    }
    removeBlock(camera) {
        let f = new Vector3();
        f.set(camera.at);
        f.sub(camera.eye);
        f.normalize();

        let tx = camera.eye.elements[0] + f.elements[0] * 1.5;
        let tz = camera.eye.elements[2] + f.elements[2] * 1.5;

        let mx = Math.floor((tx + 5) / 0.5 + 16);
        let mz = Math.floor(tz / 0.5 + 16);

        if (mx < 0 || mx >= 32 || mz < 0 || mz >= 32) return false;

        // Remove from map if it has a block
        if (this.map[mz][mx] > 0) {
            this.map[mz][mx] = 0;
            return true;
        }

        // Remove from placed objects array if it's there
        let before = this.objects.length;
        this.objects = this.objects.filter(o => !(o.x === mx && o.z === mz));
        return this.objects.length < before;
    }
    drawMap() {
        for (let x = 0; x < 32; x++) {
            for (let z = 0; z < 32; z++) {
                let height = this.map[z][x];
                if (height === 0) continue;

                for (let y = 0; y < height; y++) {
                    var wall = new Cube();
                    wall.color = [1.0, 1.0, 1.0, 1.0];

                    // Texture by height
                    if (height === 1) {
                        wall.textureNum = 1; // ground texture
                    } else if(height === 1.5){
                        wall.textureNum = Math.floor(Math.random() * 3) + 4;
                    } else if (height === 2) {
                        wall.textureNum = 3; // mid wall texture
                    } else if (height === 16) {
                        wall.textureNum = 5; // flag texture
                    } else {
                        wall.textureNum = 3; // tall wall texture
                    }
                    wall.matrix.translate(-5, -0.75, 0);
                    wall.matrix.scale(.5, .5, .5);
                    wall.matrix.translate(x - 16, y, z - 16);
                    wall.renderfast();
                }
            }
        }
        this.drawObjects();
    }
    drawObjects() {
        for (let obj of this.objects) {
            let block = new Cube();
            block.textureNum = 0;
            block.color = [0.9, 1.0, 0.9, 1.0];
            
            block.matrix.translate(-5, -0.75, 0);
            block.matrix.scale(0.5, 0.5, 0.5);
            block.matrix.translate(obj.x - 16, obj.y, obj.z - 16);
            block.renderfast();
        }
    }
    
